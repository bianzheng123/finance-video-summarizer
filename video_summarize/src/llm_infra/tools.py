"""LLM 可调用的工具 JSON 定义（DeepSeek Tool Calls 格式，见
https://api-docs.deepseek.com/guides/tool_calls）。

工具描述的唯一事实源是各工具定义里的 `function.description` 与
`parameters.*.description`（思考模式下 `tool_choice` 只能是 auto，模型是否调用
完全取决于它对这段描述的理解）。禁止在业务 `.txt` / user prompt 里再手写第二份
工具用法：通用的「工具是什么 / 参数是什么」只在这里定义一次，阶段特有的使用策略
（如 `direction` 的阶段取值语义）写在各自 task_rules 里。

约束（实测）：
- 思考模式下 `tool_choice` 只能 `"auto"`，`"required"` 与指定函数字典会被服务端拒绝。
- 模型一轮可能发出多个并行 tool_calls，执行侧必须能处理多次调用。
- 工具的 strict 归一化由 `client._as_strict_tools` 统一处理，此处按普通形态定义即可。
"""

# ---------------------------------------------------------------------------
# 工具：web_search（联网搜索）—— description 单一事实源
# ---------------------------------------------------------------------------

WEB_SEARCH_DESCRIPTION = (
    "联网搜索，返回相关网页的标题与摘要。"
    "当你无法仅凭 [DATA] 上下文确定某个黑话 / 简称 / 疑似 ASR 误识词的真实含义时，"
    "**必须**调用本工具核实，不要凭训练数据猜测——"
    "训练数据里的旧闻关联经常与本次字幕的实际语境冲突。"
    "可以在同一轮里发起多次调用来并行验证不同假设。"
)

# ---------------------------------------------------------------------------
# 工具：row_pinyin（行读音）—— description 单一事实源
# ---------------------------------------------------------------------------

ROW_PINYIN_DESCRIPTION = (
    "查询 [DATA] 中指定行的**整行拼音读音**（带声调）。"
    "怀疑某处是 ASR 误识时，先用本工具取读音，再据读音构造搜索词——"
    "搜 'shèng hóng 科技 PCB' 往往比搜错字字面 '深宏' 有效得多。"
    "读音由拼音库确定性算出，是事实，可直接采信。"
    "也可用它核对词边界：上一阶段圈出的片段边界可能本身就是错的。"
    "一次可传多行，按需调用，不必逐行分开调。"
)

# ---------------------------------------------------------------------------
# 工具 JSON 定义
# ---------------------------------------------------------------------------

# 联网搜索：2_3 联网确认、4_3 精确去重、4_5 候选精筛、4_6 关系去环共用。
WEB_SEARCH_TOOL = {
    "type": "function",
    "function": {
        "name": "web_search",
        "description": WEB_SEARCH_DESCRIPTION,
        "parameters": {
            "type": "object",
            "properties": {
                "query": {
                    "type": "string",
                    "description": (
                        "搜索词。必须包含待消歧的词本身，"
                        "并拼上 2-3 个来自 [DATA] 上下文的产业 / 板块 / 标的 / 事件线索词。"
                        "这些线索词必须在 [DATA] 里逐字出现过，禁止脑补。"
                        "例：'盛虹 PCB 覆铜板'、'SST 电网 储能'。"
                        "若疑似是英文术语的中文谐音，把英文候选放在最前面，例：'CUDA NVIDIA GPU 兼容'。"
                    ),
                },
                "direction": {
                    "type": "string",
                    "description": (
                        "本次搜索要验证的「方向」标签，格式 `对象标识:方向类型`（方向类型见任务规则）。"
                        "同一方向只允许搜一次，系统按此标签去重：相同方向重复调用会被拒绝。"
                        "务必用稳定、一致的措辞，不要换词表达同一方向。"
                    ),
                },
            },
            "required": ["query", "direction"],
        },
    },
}

# 行读音查询：2_3 联网确认用。纯本地确定性计算（pypinyin），不走网络、不占配额。
#
# 为什么值得做成工具而不是一次性全塞进 prompt：2_3 是多轮 ReAct，模型往往在搜了
# 一轮之后才意识到"这个词的边界可能切错了"或"该按读音而不是字面去搜"。此时它需要
# **按需**取读音，而预先塞入的读音只覆盖进入本阶段时已知的那几行。
ROW_PINYIN_TOOL = {
    "type": "function",
    "function": {
        "name": "row_pinyin",
        "description": ROW_PINYIN_DESCRIPTION,
        "parameters": {
            "type": "object",
            "properties": {
                "row_ids": {
                    "type": "array",
                    "items": {"type": "integer"},
                    "description": (
                        "要查读音的 rowID 数组，必须是 [DATA] 里真实存在的行号。"
                    ),
                },
            },
            "required": ["row_ids"],
        },
    },
}
